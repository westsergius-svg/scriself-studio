/// <summary>
/// Перевод интерфейса. Ключом служит русская строка: так разметку можно
/// переводить без отдельных ключей, а отсутствующий перевод остаётся русским.
/// </summary>
public sealed class LocalizationManager : INotifyPropertyChanged
{
    public static LocalizationManager Instance { get; } = new();

    private string _language = "ru-RU";

    private LocalizationManager()
    {
    }

    public event PropertyChangedEventHandler? PropertyChanged;

    /// <summary>Текущий код языка; привязки обновляются по этому свойству.</summary>
    public string Language => _language;

    public bool IsEnglish => _language.StartsWith("en", StringComparison.OrdinalIgnoreCase);

    internal void SetLanguage(string language)
    {
        if (string.Equals(_language, language, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        _language = language;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Language)));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IsEnglish)));
    }

    /// <summary>Перевод строки; неизвестная строка возвращается как есть.</summary>
    public string Translate(string source)
    {
        if (!IsEnglish)
        {
            return source;
        }

        if (English.TryGetValue(source, out var translated))
        {
            return translated;
        }

        return Extra.TryGetValue(source, out translated) ? translated : source;
    }

