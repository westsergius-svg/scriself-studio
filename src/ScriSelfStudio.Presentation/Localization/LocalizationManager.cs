/// <summary>Короткий доступ к переводу из моделей экранов.</summary>
public static class Loc
{
    public static string T(string source) => LocalizationManager.Instance.Translate(source);

    public static string F(string format, params object?[] arguments) =>
        string.Format(CultureInfo.CurrentCulture, LocalizationManager.Instance.Translate(format), arguments);

    /// <summary>Выбирает форму числа по языку интерфейса, а не по русскому окончанию.</summary>
    public static string Plural(int count, string one, string few, string many)
    {
        var localization = LocalizationManager.Instance;
        if (localization.IsEnglish)
        {
            return T(count == 1 ? one : many);
        }

        if (localization.IsChinese)
        {
            return T(many);
        }

        var remainder = count % 100;
        return T(remainder is >= 11 and <= 14 ? many : (count % 10) switch
        {
            1 => one,
            2 or 3 or 4 => few,
            _ => many,
        });
    }

    public static string Count(int count, string one, string few, string many) =>
        $"{count.ToString("N0", CultureInfo.CurrentCulture)} {Plural(count, one, few, many)}";
}
